#!/usr/bin/env node
// Compiles skills/<name>/SKILL.md into packages/vdd-mcp/src/generated/skills.ts.
//
// The deployed function is `api/` and its siblings: it carries no copy of
// skills/, so the manifest is compiled in rather than loaded at runtime.
// It is committed, like index.html, and regenerated deliberately:
//
//   node scripts/gen-skill-manifest.mjs          # write
//   node scripts/gen-skill-manifest.mjs --check  # exit 1 if the file would change
//
// `skill-manifest.test.ts` runs the --check form, so a hand-edited manifest or a
// skill edited without regenerating fails the suite rather than shipping stale.

import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const skillsDir = join(root, 'skills');
const output = join(root, 'packages/vdd-mcp/src/generated/skills.ts');

const FRONTMATTER = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/;

/** `name:` and `description:` from the leading YAML block; the body is everything after it. */
function parse(text) {
  const match = FRONTMATTER.exec(text);
  if (!match) throw new Error('SKILL.md has no frontmatter block');

  const fields = {};
  for (const line of match[1].split(/\r?\n/)) {
    const field = /^([a-z][a-z-]*):\s*(.*)$/.exec(line);
    if (field) fields[field[1]] = field[2];
  }
  return { fields, body: text.slice(match[0].length).trim() };
}

const entries = [];
const names = new Set();
// Codepoint order, not locale order: `localeCompare` varies with the host's collation,
// and a `--check` that disagrees with itself across machines is worse than no check.
const ordered = (await readdir(skillsDir, { withFileTypes: true })).sort((a, b) =>
  a.name < b.name ? -1 : a.name > b.name ? 1 : 0,
);
for (const dirent of ordered) {
  if (!dirent.isDirectory()) continue;
  const text = await readFile(join(skillsDir, dirent.name, 'SKILL.md'), 'utf8');
  const { fields } = parse(text);
  const name = fields.name ?? dirent.name;
  // A duplicate name would make one of the pair unreachable through `getSkill`.
  if (names.has(name)) throw new Error(`duplicate skill name: ${name}`);
  names.add(name);
  entries.push({
    name,
    description: fields.description ?? '',
    text,
    sha256: createHash('sha256').update(text).digest('hex'),
    size: Buffer.byteLength(text),
    uri: `skill://${name}/SKILL.md`,
  });
}

const rendered = `// Generated by scripts/gen-skill-manifest.mjs — do not edit by hand.
// Regenerate with: node scripts/gen-skill-manifest.mjs

export interface SkillManifestEntry {
  readonly name: string;
  readonly description: string;
  /** The whole SKILL.md, frontmatter included: the skills extension parses it. */
  readonly text: string;
  readonly sha256: string;
  readonly size: number;
  readonly uri: string;
}

export const SKILLS: readonly SkillManifestEntry[] = ${JSON.stringify(entries, null, 2)};
`;

if (process.argv.includes('--check')) {
  const current = await readFile(output, 'utf8').catch(() => null);
  if (current !== rendered) {
    process.stderr.write(
      `skills.ts is stale: run \`node scripts/gen-skill-manifest.mjs\` and commit the result.\n`,
    );
    process.exit(1);
  }
  process.stdout.write(`skills.ts is current (${entries.length} skills)\n`);
} else {
  await writeFile(output, rendered);
  process.stdout.write(`wrote ${entries.length} skills to ${output}\n`);
}
