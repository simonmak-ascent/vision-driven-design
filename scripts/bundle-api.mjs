#!/usr/bin/env node
// Compiles the MCP server into one CommonJS file under `api/`, so the Vercel
// function is self-contained.
//
// Why a committed bundle rather than a build step: `includeFiles` pointed at
// `packages/*/dist` was present in `vercel.json` and the file was still absent
// from `/var/task` — production returned `Cannot find module
// '/var/task/packages/vdd-mcp/dist/handler.js'`. Build order on Vercel is
// undocumented (one report says `/api` is scanned before the build step), so
// anything produced during the build may not exist when the function is
// packaged. A file committed to `api/` exists at every moment of the deploy.
//
//   node scripts/bundle-api.mjs          # write api/_vdd-core.cjs
//   node scripts/bundle-api.mjs --check  # exit 1 if it would change
//
// The bundle is generated, never edited: `--check` compares the committed bytes
// against a fresh build, and `hosted-bundle.test.ts` runs it.

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import * as esbuild from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const entry = new URL('packages/vdd-mcp/dist/handler.js', `file://${root}`);
const output = new URL('api/_vdd-core.cjs', `file://${root}`);

/**
 * `absWorkingDir` and `banner` are pinned so two runs produce identical bytes:
 * esbuild records paths relative to the working directory, and the banner is
 * the only place the toolchain version appears.
 */
const options = {
  entryPoints: [fileURLToPath(entry)],
  absWorkingDir: root,
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  // `eof`, not `none`: the bundle inlines MIT/BSD code (zod, ajv, the MCP SDK) into a
  // file committed to a public repository, and those licences require the notice to
  // travel with the copy. `eof` appends them once, deterministically.
  legalComments: 'eof',
  logLevel: 'warning',
  banner: { js: `// Generated by scripts/bundle-api.mjs with esbuild@${esbuild.version} — do not edit.` },
};

async function render() {
  const built = await esbuild.build({ ...options, write: false });
  return built.outputFiles[0].text;
}

async function main() {
  const check = process.argv.includes('--check');

  try {
    await readFile(entry);
  } catch {
    process.stderr.write(
      'packages/vdd-mcp/dist/handler.js is missing — run `pnpm -r build` first.\n',
    );
    process.exit(1);
  }

  const rendered = await render();
  const current = await readFile(output, 'utf8').catch(() => null);

  if (check) {
    if (current === null) {
      process.stderr.write('api/_vdd-core.cjs is missing — run `pnpm bundle:api` and commit it.\n');
      process.exit(1);
    }
    const banner = /esbuild@(\d+\.\d+\.\d+)/.exec(current)?.[1];
    if (banner !== esbuild.version) {
      process.stderr.write(
        `api/_vdd-core.cjs was built with esbuild@${banner ?? 'unknown'}, ` +
          `but esbuild@${esbuild.version} is installed — regenerate it.\n`,
      );
      process.exit(1);
    }
    if (current !== rendered) {
      process.stderr.write(
        'api/_vdd-core.cjs is stale — run `node scripts/bundle-api.mjs` and commit the result.\n',
      );
      process.exit(1);
    }
    process.stdout.write(
      `api/_vdd-core.cjs is current (${rendered.length} bytes, sha256 ${createHash('sha256').update(rendered).digest('hex').slice(0, 12)})\n`,
    );
    return;
  }

  if (current === rendered) {
    process.stdout.write(`api/_vdd-core.cjs is unchanged (${rendered.length} bytes)\n`);
    return;
  }
  await writeFile(output, rendered);
  process.stdout.write(`wrote api/_vdd-core.cjs (${rendered.length} bytes)\n`);
}

await main();
